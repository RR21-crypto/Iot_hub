"""Draw the weather icons and write them as LVGL images (C arrays).

Usage: python make_weather_icons.py [output .c]   (default: main/assets/weather_icons.c)
Icons are drawn 4x larger and scaled down for smooth edges, then stored as ARGB8888
(LVGL byte order B, G, R, A). Each one is 96x96 = 36 KB of flash.
"""
import math
import os
import sys
from PIL import Image, ImageDraw

SIZE = 96
SS = 4                      # supersampling factor
S = SIZE * SS

SUN = (255, 193, 7, 255)
CLOUD = (236, 239, 244, 255)
CLOUD_BACK = (176, 190, 197, 255)
CLOUD_DARK = (120, 144, 156, 255)
RAIN = (79, 195, 247, 255)
BOLT = (255, 213, 79, 255)
SNOW = (255, 255, 255, 255)
FOG = (176, 190, 197, 255)


def px(v):
    """Relative coordinate (0..1) to supersampled pixels."""
    return v * S


def circle(d, cx, cy, r, color):
    d.ellipse([px(cx - r), px(cy - r), px(cx + r), px(cy + r)], fill=color)


def sun(d, cx, cy, r):
    for i in range(8):
        a = i * math.pi / 4
        x1, y1 = cx + math.cos(a) * r * 1.4, cy + math.sin(a) * r * 1.4
        x2, y2 = cx + math.cos(a) * r * 1.85, cy + math.sin(a) * r * 1.85
        d.line([px(x1), px(y1), px(x2), px(y2)], fill=SUN, width=int(px(r * 0.28)))
    circle(d, cx, cy, r, SUN)


def cloud(d, ox=0.0, oy=0.0, k=1.0, color=CLOUD):
    """Cloud made of three circles on a rounded base; (ox, oy) shifts it, k scales it."""
    def c(x, y, r):
        circle(d, 0.5 + (x - 0.5) * k + ox, 0.5 + (y - 0.5) * k + oy, r * k, color)
    c(0.33, 0.58, 0.16)
    c(0.53, 0.47, 0.22)
    c(0.72, 0.60, 0.14)
    x0, x1 = 0.5 + (0.17 - 0.5) * k + ox, 0.5 + (0.86 - 0.5) * k + ox
    y0, y1 = 0.5 + (0.56 - 0.5) * k + oy, 0.5 + (0.74 - 0.5) * k + oy
    d.rounded_rectangle([px(x0), px(y0), px(x1), px(y1)], radius=px(0.09 * k), fill=color)


def drops(d, color, xs=(0.36, 0.52, 0.68)):
    for x in xs:
        d.line([px(x + 0.03), px(0.74), px(x - 0.03), px(0.88)], fill=color, width=int(px(0.045)))


def icon_clear(d):
    sun(d, 0.5, 0.5, 0.2)


def icon_partly(d):
    sun(d, 0.36, 0.36, 0.15)
    cloud(d, 0.06, 0.08, 0.82)


def icon_cloudy(d):
    cloud(d, 0.1, -0.1, 0.7, CLOUD_BACK)
    cloud(d, -0.03, 0.06, 0.9)


def icon_fog(d):
    cloud(d, 0, -0.12, 0.8)
    for i, y in enumerate((0.72, 0.82)):
        x0 = 0.2 + i * 0.08
        d.rounded_rectangle([px(x0), px(y), px(x0 + 0.56), px(y + 0.05)], radius=px(0.025), fill=FOG)


def icon_rain(d):
    cloud(d, 0, -0.12, 0.9)
    drops(d, RAIN)


def icon_thunder(d):
    cloud(d, 0, -0.12, 0.9, CLOUD_DARK)
    bolt = [(0.54, 0.6), (0.4, 0.8), (0.5, 0.8), (0.44, 0.95), (0.62, 0.72), (0.52, 0.72), (0.6, 0.6)]
    d.polygon([(px(x), px(y)) for x, y in bolt], fill=BOLT)


def icon_snow(d):
    cloud(d, 0, -0.12, 0.9)
    for x, y in ((0.34, 0.8), (0.5, 0.88), (0.66, 0.8)):
        circle(d, x, y, 0.035, SNOW)


ICONS = {
    "clear": icon_clear,
    "partly": icon_partly,
    "cloudy": icon_cloudy,
    "fog": icon_fog,
    "rain": icon_rain,
    "thunder": icon_thunder,
    "snow": icon_snow,
}


def render(fn):
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    fn(ImageDraw.Draw(img))
    return img.resize((SIZE, SIZE), Image.LANCZOS)


def to_c_array(name, img):
    rgba = img.tobytes()
    data = bytearray(len(rgba))
    data[0::4], data[1::4], data[2::4], data[3::4] = rgba[2::4], rgba[1::4], rgba[0::4], rgba[3::4]  # LVGL: B, G, R, A
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
    return (f"static const uint8_t {name}_map[] = {{\n" + "\n".join(lines) + "\n};\n\n"
            f"const lv_image_dsc_t weather_icon_{name} = {{\n"
            f"    .header = {{\n"
            f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"        .cf = LV_COLOR_FORMAT_ARGB8888,\n"
            f"        .w = {SIZE},\n"
            f"        .h = {SIZE},\n"
            f"        .stride = {SIZE * 4},\n"
            f"    }},\n"
            f"    .data_size = sizeof({name}_map),\n"
            f"    .data = {name}_map,\n"
            f"}};\n\n")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "main", "assets", "weather_icons.c")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    preview = Image.new("RGBA", (SIZE * len(ICONS), SIZE), (18, 16, 26, 255))
    body = ""
    for i, (name, fn) in enumerate(ICONS.items()):
        img = render(fn)
        preview.alpha_composite(img, (i * SIZE, 0))
        body += to_c_array(name, img)
    with open(out, "w", newline="\n") as f:
        f.write("/*\n * Weather icons, generated by tools/make_weather_icons.py - do not edit.\n */\n"
                "#include \"weather_icons.h\"\n\n" + body)
    preview.save(os.path.join(here, "weather_icons_preview.png"))
    print(f"{out}: {len(ICONS)} icons, preview in tools/weather_icons_preview.png")


main()
